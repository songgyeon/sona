export const WORKS: readonly Work[] = [
  ...MOVIES.map(([title, year]): Work => ({ kind: 'movie', title, by: '', year })),
  ...DRAMAS.map(([title, year]): Work => ({ kind: 'drama', title, by: '', year })),
  ...SONGS.map(([title, by]): Work => ({ kind: 'song', title, by })),
  ...BOOKS.map(([title, by]): Work => ({ kind: 'book', title, by })),
];

/** 견주는 모양: 띄어쓰기와 문장 부호를 떼고 작은 글자로. 「너의 이름은」과 「너의 이름은.」은 같은 작품이다 */
export const workKey = (s: string): string =>
  s
    .normalize('NFC')
    .toLowerCase()
    .replace(/[\s.,!?·:;'"‘’“”\-–—~()[\]<>「」『』《》〈〉/&]+/g, '');

/** 이 제목의 작품. kinds 가운데서만 찾는다. 없으면 null */
export function findWork(title: string, kinds: readonly WorkKind[]): Work | null {
  const t = workKey(title);
  if (!t) return null;
  return WORKS.find((w) => kinds.includes(w.kind) && workKey(w.title) === t) ?? null;
}

/** 대사 모델에게 보여 줄 몇 편. 부를 때마다 섞는다 — 날마다 다른 것이 눈에 든다 */
export function someWorks(kind: WorkKind, n: number, rand: () => number = Math.random): Work[] {
  const pool = WORKS.filter((w) => w.kind === kind);
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [pool[i], pool[j]] = [pool[j]!, pool[i]!];
  }
  return pool.slice(0, n);
}

/** 대사 모델이 고른 영화·드라마·노래·책을 목록에서 찾아 정식 제목과 만든 사람으로 적는다. 목록에 없으면 null.
    영화로 적었어도 목록에 드라마로 있으면 드라마다. 그 밖의 피드는 그대로 */
export function realize(d: PostData): PostData | null {
  if (d.kind === 'watch') {
    const w = findWork(d.title, ['movie', 'drama']);
    if (!w) return null;
    const drama = w.kind === 'drama';
    return { ...d, form: drama ? 'drama' : 'movie', title: w.title, ep: drama ? d.ep : '' };
  }
  if (d.kind === 'song') {
    const w = findWork(d.title, ['song']);
    return w ? { ...d, title: w.title, artist: w.by } : null;
  }
  if (d.kind === 'book') {
    const w = findWork(d.title, ['book']);
    return w ? { ...d, title: w.title, author: w.by } : null;
  }
  return d;
}
